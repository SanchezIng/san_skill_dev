// Instala los hooks de pre-commit (gitleaks) tras cada instalacion de
// dependencias. SOLO PARA STACKS NODE: lo llama el script `prepare` de
// package.json, que npm/pnpm/yarn ejecutan solos tras `install`.
//
//   "scripts": { "prepare": "node scripts/install-git-hooks.mjs" }
//
// Por que existe: `pre-commit install` era un paso manual por clon y nada
// comprobaba que se hubiera hecho, asi que un clon nuevo commiteaba SIN escaneo
// de secretos y el commit no decia nada. El hook de arranque del kit ya delata
// a quien no los tenga; esto es la otra mitad — que no haga falta acordarse.
//
// El CI no es equivalente ni cuando existe: el hook impide que el secreto ENTRE
// en la historia; el CI lo caza cuando ya hay que reescribirla o rotar la
// credencial.
//
// Regla del silencio: este script NUNCA se calla cuando no hizo su trabajo. Y no
// da por bueno el exit 0 de `pre-commit install`: relee el hook del disco y
// exige la marca que genera la herramienta.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

// La escribe la propia herramienta en la cabecera del hook generado.
const MARCA = "File generated by pre-commit";

function avisar(motivo, comoArreglarlo) {
  console.error("");
  console.error(
    "  ⚠️  LOS HOOKS DE GIT NO QUEDARON INSTALADOS — commitearas SIN escaneo de secretos.",
  );
  console.error(`      Motivo: ${motivo}`);
  console.error(`      Arreglo: ${comoArreglarlo}`);
  console.error("      Por que importa: el hook impide que un secreto ENTRE en la historia;");
  console.error("      el CI solo lo caza cuando ya hay que reescribirla o rotar la credencial.");
  console.error("");
}

// Devuelve la salida, o null si git dice que no. Lanza si git no se pudo ni
// ejecutar: "no pude preguntar" no puede confundirse con "la respuesta es no"
// — es exactamente el defecto que esta tarea existe para matar.
function git(args) {
  const r = spawnSync("git", args, { encoding: "utf8" });
  if (r.error) throw r.error;
  return r.status === 0 ? r.stdout.trim() : null;
}

// 1. Sin repo git no hay hooks que instalar (instalacion desde tarball, contenedor
//    sin .git). No es un fallo, pero se dice: callarse aqui es como no correr.
try {
  if (git(["rev-parse", "--git-dir"]) === null) {
    console.log("hooks: no es un repo git — nada que instalar.");
    process.exit(0);
  }
} catch (e) {
  avisar(
    `no se pudo ejecutar git (${e.code ?? e.message}), asi que no se si hay hooks o no`,
    "comprueba que git esta en el PATH y repite la instalacion de dependencias",
  );
  process.exit(0);
}

// 2. En CI los hooks locales no aportan (el runner no commitea) y ademas el
//    escaneo lo hace gitleaks-action sobre el rango de commits del PR (ci.yml).
if (process.env.CI) {
  console.log("hooks: CI detectado — el escaneo lo hace gitleaks-action, no el hook local.");
  process.exit(0);
}

// 3. `pre-commit` tiene que estar en el PATH. Si no esta, no se instala nada:
//    aqui es donde un `|| true` silencioso reproduciria el bug original.
// Comando en una sola cadena y no (cmd, [args]): con `shell` esa mezcla dispara
// un DeprecationWarning de Node en cada instalacion, y el ruido tapa el aviso
// que este script existe para dar. `shell` hace falta para los shims .cmd/.bat.
if (spawnSync("pre-commit --version", { shell: true }).status !== 0) {
  avisar(
    "`pre-commit` no esta en el PATH",
    "instalalo (`pipx install pre-commit` o `pip install pre-commit`) y repite la instalacion de dependencias",
  );
  process.exit(0);
}

const instalacion = spawnSync("pre-commit install", {
  stdio: "inherit",
  shell: true,
});

// 4. Verificar el EFECTO, no el exit code (CLAUDE.md: "exit 0 de una herramienta
//    != tarea hecha"). `core.hooksPath` puede redirigir el directorio de hooks.
// El try/catch cierra el invariante "prepare nunca lanza" (decision 1 del PR #63):
// si git dejara de ser ejecutable entre el paso 1 y aqui, `git()` lanzaria sin
// captura y la instalacion reventaria con stack trace — justo lo que evitamos al
// devolver 0: romper `install` tumbaria el CI y a quien no tenga Python.
let dirHooks;
try {
  dirHooks =
    git(["config", "--get", "core.hooksPath"]) ?? git(["rev-parse", "--git-path", "hooks"]);
} catch (e) {
  avisar(
    `no se pudo ejecutar git (${e.code ?? e.message}), asi que no se donde deberia estar el hook`,
    "comprueba que git esta en el PATH y repite la instalacion de dependencias",
  );
  process.exit(0);
}
const rutaHook = dirHooks ? join(dirHooks, "pre-commit") : null;

if (!rutaHook || !existsSync(rutaHook)) {
  avisar(
    `\`pre-commit install\` termino con codigo ${instalacion.status} pero no hay hook en ${rutaHook ?? "(ruta desconocida)"}`,
    "ejecuta `pre-commit install` a mano y mira que dice",
  );
  process.exit(0);
}

if (!readFileSync(rutaHook, "utf8").includes(MARCA)) {
  avisar(
    `${rutaHook} existe pero no lo genero pre-commit (hook propio o de otra herramienta)`,
    "revisalo: si es tuyo, integra pre-commit en el; si no, borralo y repite la instalacion de dependencias",
  );
  process.exit(0);
}

console.log(`hooks: escaneo de secretos activo en ${rutaHook} ✓`);
